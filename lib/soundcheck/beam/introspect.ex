defmodule Soundcheck.Beam.Introspect do
  @moduledoc false
  # Probes compiled modules for LiveView facts.
  #
  # Every probe loads the module on demand, validates the shape of what it
  # reads, and computes once per module per run through `Soundcheck.Once`.
  # Several sources are private LiveView or Phoenix API (marked below), so a
  # shape that does not match what LiveView 1.1 and 1.2 produce returns
  # `{:error, :unexpected_shape}` instead of a guess.
  #
  # Common errors:
  #
  #   * `{:error, :not_loadable}` - the module cannot be compiled or found.
  #   * `{:error, :unexpected_shape}` - the module answered, but not in a
  #     shape this version of soundcheck understands.

  alias Soundcheck.Once

  @type mount_hook :: {module(), term()}

  defmodule LiveInfo do
    @moduledoc false
    # What `__live__/0` says about a module: a LiveView (`:view`) with its
    # module-level `on_mount` hooks, or a LiveComponent with none.
    @enforce_keys [:kind, :on_mount]
    defstruct [:kind, :on_mount]

    @type t :: %__MODULE__{
            kind: :view | :component,
            on_mount: [Soundcheck.Beam.Introspect.mount_hook()]
          }
  end

  @type live_info :: LiveInfo.t()

  @type component :: %{kind: :def | :defp, line: pos_integer(), attrs: [map()], slots: [map()]}

  @type route :: %{
          path: String.t(),
          verb: atom(),
          live_view: module(),
          action: atom() | nil,
          live_session: atom(),
          on_mount: [mount_hook()]
        }

  @doc """
  Returns whether `module` is a LiveView or LiveComponent and, for a
  LiveView, its module-level `on_mount` hooks.

  Reads `__live__/0`, generated `@doc false` by LiveView [private]. Returns
  `{:error, :not_live}` for any other module.
  """
  @spec live(module()) ::
          {:ok, live_info()} | {:error, :not_loadable | :not_live | :unexpected_shape}
  def live(module) do
    probe({:live, module}, module, :__live__, 0, fn
      %{kind: :view, lifecycle: %{mount: hooks}} ->
        with {:ok, hooks} <- mount_hooks(hooks),
             do: {:ok, %LiveInfo{kind: :view, on_mount: hooks}}

      %{kind: :component} ->
        {:ok, %LiveInfo{kind: :component, on_mount: []}}

      _other ->
        {:error, :unexpected_shape}
    end)
    |> case do
      {:error, :undefined} -> {:error, :not_live}
      result -> result
    end
  end

  @doc """
  Returns the function components `module` declares with `attr` or `slot`.

  Reads `__components__/0` [private: generated by
  `Phoenix.Component.Declarative`]. Functions without any declaration do
  not appear. Returns `{:error, :no_components}` for a module that declares
  none.
  """
  @spec components(module()) ::
          {:ok, %{atom() => component()}}
          | {:error, :not_loadable | :no_components | :unexpected_shape}
  def components(module) do
    probe({:components, module}, module, :__components__, 0, fn
      components when is_map(components) ->
        if Enum.all?(components, &component?/1),
          do: {:ok, components},
          else: {:error, :unexpected_shape}

      _other ->
        {:error, :unexpected_shape}
    end)
    |> case do
      {:error, :undefined} -> {:error, :no_components}
      result -> result
    end
  end

  @doc """
  Returns the live routes of `router`.

  Reads the router's `__routes__/0` [private: `Phoenix.Router.routes/1`
  is its public wrapper, but calling it would make Phoenix a dependency]
  and the `metadata.phoenix_live_view` tuple that `Phoenix.LiveView.Router`
  attaches to each live route [private]. A route outside any `live_session`
  reports session `:default` with no `on_mount` hooks, the same as an
  explicit `live_session :default` without hooks.
  """
  @spec live_routes(module()) ::
          {:ok, [route()]} | {:error, :not_loadable | :not_a_router | :unexpected_shape}
  def live_routes(router) do
    probe({:live_routes, router}, router, :__routes__, 0, fn
      routes when is_list(routes) ->
        routes
        |> Enum.filter(&match?(%{metadata: %{phoenix_live_view: _}}, &1))
        |> collect(&live_route/1)

      _other ->
        {:error, :unexpected_shape}
    end)
    |> case do
      {:error, :undefined} -> {:error, :not_a_router}
      result -> result
    end
  end

  @doc """
  Returns `true` when Phoenix LiveView is loadable in the VM running the
  analysis, which requires the host project's dependencies to be compiled.
  """
  @spec live_view_available?() :: boolean()
  def live_view_available?,
    do: Once.run({__MODULE__, :live_view_available?}, fn -> loaded?(Phoenix.LiveView) end)

  @doc "Returns the public functions `module` exports, from `__info__/1`."
  @spec functions(module()) :: {:ok, MapSet.t({atom(), arity()})} | {:error, :not_loadable}
  def functions(module) do
    Once.run({__MODULE__, :functions, module}, fn ->
      if loaded?(module),
        do: {:ok, MapSet.new(module.__info__(:functions))},
        else: {:error, :not_loadable}
    end)
  end

  # Loads `module`, checks that it exports `fun/arity`, calls it, and hands
  # the result to `decode`, whose last clause must return
  # `{:error, :unexpected_shape}`. An undefined probe function returns
  # `{:error, :undefined}` for the caller to rename.
  defp probe(key, module, fun, arity, decode) do
    Once.run({__MODULE__, key}, fn ->
      cond do
        not loaded?(module) -> {:error, :not_loadable}
        not function_exported?(module, fun, arity) -> {:error, :undefined}
        true -> decode.(apply(module, fun, []))
      end
    end)
  end

  # Maps `fun` over `items`, stopping at the first error.
  defp collect(items, fun) do
    Enum.reduce_while(items, {:ok, []}, fn item, {:ok, acc} ->
      case fun.(item) do
        {:ok, value} -> {:cont, {:ok, [value | acc]}}
        error -> {:halt, error}
      end
    end)
    |> case do
      {:ok, values} -> {:ok, Enum.reverse(values)}
      error -> error
    end
  end

  defp loaded?(module), do: match?({:module, ^module}, Code.ensure_loaded(module))

  defp live_route(%{path: path, verb: verb, metadata: %{phoenix_live_view: live}}) do
    case live do
      {view, action, _opts, %{name: session, extra: extra}} when is_atom(view) ->
        with {:ok, hooks} <- mount_hooks(Map.get(extra, :on_mount, [])) do
          {:ok,
           %{
             path: path,
             verb: verb,
             live_view: view,
             action: action,
             live_session: session,
             on_mount: hooks
           }}
        end

      _other ->
        {:error, :unexpected_shape}
    end
  end

  defp live_route(_route), do: {:error, :unexpected_shape}

  defp mount_hooks(hooks) when is_list(hooks) do
    if Enum.all?(hooks, &match?(%{id: {module, _arg}} when is_atom(module), &1)),
      do: {:ok, Enum.map(hooks, & &1.id)},
      else: {:error, :unexpected_shape}
  end

  defp mount_hooks(_hooks), do: {:error, :unexpected_shape}

  defp component?({name, %{kind: kind, attrs: attrs, slots: slots}})
       when is_atom(name) and kind in [:def, :defp] and is_list(attrs) and is_list(slots),
       do: true

  defp component?(_entry), do: false
end
